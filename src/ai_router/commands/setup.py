"""Handlers for `init` (auto-generate config.toml) and `doctor` / `status --check` diagnostics."""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path

from ai_router.config import (
    DEFAULT_CANDIDATES,
    DEFAULT_SUPPORTED_TOOLS,
    AppConfig,
    get_active_config,
    get_default_config_path,
    get_log_file,
    resolve_config_path,
)
from ai_router.credits import format_remaining_cooldown, get_exhausted_tools
from ai_router.errors import AiRouteError
from ai_router.router import resolve_router_service
from ai_router.security import ensure_private_dir, ensure_private_file
from ai_router.tools import BUILTIN_TOOL_ADAPTERS, get_installed_tools, is_tool_installed


def run_diagnostics(config: AppConfig | None = None) -> None:
    """Print environment diagnostics: installed CLIs, active config, router, candidates, credits."""
    cfg = config or get_active_config()
    cfg_path = resolve_config_path()
    exhausted = get_exhausted_tools()
    router_choice = resolve_router_service(cfg, excluded_tools=set(exhausted.keys()))

    print("=== ai-route Environment Diagnostics ===")
    print(f"Config file : {cfg_path if cfg_path else f'(none — using defaults; default path: {get_default_config_path()})'}")
    print(f"Log file    : {get_log_file()}")
    print(f"Auto-detect : {'enabled' if cfg.auto_detect_tools else 'disabled'}")
    print(f"agy ACP mode: {cfg.agy_acp_mode} (always uses `agy acp --stdio`)")
    if router_choice:
        print(f"Router      : {router_choice[0]}:{router_choice[1]}")
    else:
        print("Router      : (none available — will fall back directly to candidates)")

    print("\n--- Core Dependencies ---")
    for dep in ("git", "tmux", "gh"):
        found = shutil.which(dep)
        mark = f"OK ({found})" if found else "missing"
        print(f"  {dep:<10}: {mark}")

    print("\n--- Agent CLIs ---")
    for tool in cfg.supported_tools:
        adapter = BUILTIN_TOOL_ADAPTERS.get(tool)
        binary = adapter.binary if adapter else tool
        found = shutil.which(binary)
        mode_note = " [ACP]" if (adapter and adapter.uses_acp) else ""
        if tool in exhausted:
            rem = format_remaining_cooldown(str(exhausted[tool].get("until") or ""))
            credit_note = f"  [EXHAUSTED: {rem} left]"
        else:
            credit_note = ""
        status_str = f"OK ({found}){mode_note}{credit_note}" if found else "not installed"
        print(f"  {tool:<10}: {status_str}")

    print("\n--- Active Candidates ---")
    for c in cfg.candidates:
        installed = is_tool_installed(c["tool"])
        in_cooldown = c["tool"] in exhausted
        flags = []
        if not installed:
            flags.append("uninstalled")
        if in_cooldown:
            flags.append("credit-exhausted")
        suffix = f" ({', '.join(flags)})" if flags else ""
        eff = f", effort={c['effort']}" if c.get("effort") else ""
        print(f"  [{c['difficulty']:<6}] {c['tool']}:{c['model']}{eff}{suffix}")


def render_initial_config(installed_tools: tuple[str, ...]) -> str:
    """Generate a ready-to-use TOML configuration tailored to the installed agent CLIs."""
    tools = installed_tools if installed_tools else ("opencode", "agy", "claude")
    allowed = [
        f"{c['tool']}:{c['model']}"
        for c in DEFAULT_CANDIDATES
        if c["tool"] in tools
    ]
    router_tool = "opencode" if "opencode" in tools else tools[0]
    fallback_order = [t for t in ("opencode", "agy", "copilot", "claude", "codex") if t in tools]
    fb_cand = next((c for c in DEFAULT_CANDIDATES if c["tool"] in tools), DEFAULT_CANDIDATES[0])

    lines = [
        "# ai-route configuration (generated by `ai-route init`)",
        "# Priority: CLI args > Environment variables > This file > Built-in defaults",
        "",
        f"supported_tools = {list(DEFAULT_SUPPORTED_TOOLS)!r}".replace("'", '"'),
        "auto_detect_tools = true",
        "",
        "# Detected installed services on this machine:",
        "allowed_models = [",
    ]
    for pair in allowed:
        lines.append(f'    "{pair}",')
    lines.extend(
        [
            "]",
            "",
            "[fallback]",
            f'tool = "{fb_cand["tool"]}"',
            f'model = "{fb_cand["model"]}"',
            f'difficulty = "{fb_cand["difficulty"]}"',
            f'effort = "{fb_cand["difficulty"]}"',
            "",
            "[runtime]",
            f'router_tool = "{router_tool}"',
            f"router_fallback_tools = {fallback_order!r}".replace("'", '"'),
            'agy_acp_mode = "auto"  # agy always uses ACP mode (auto|accept-edits|default|plan)',
            'copilot_permission_flag = "--allow-all-tools"',
            "credit_cooldown_sec = 3600.0",
            "",
            "[defaults]",
            "# Uncomment to set your everyday CLI defaults:",
            "# worktree = true",
            "# auto = false",
            "# split = false",
            "# plan_first = true",
            'acp_mode = "auto"',
            "",
        ]
    )
    return "\n".join(lines)


def cmd_doctor(_args: argparse.Namespace) -> None:
    """Run environment and configuration diagnostics."""
    run_diagnostics()


def cmd_init(args: argparse.Namespace) -> None:
    """Detect installed agent CLIs and generate `~/.config/ai-route/config.toml`."""
    target = Path(args.output).expanduser() if args.output else get_default_config_path()
    if target.exists() and not args.force:
        raise AiRouteError(
            f"Configuration file already exists: {target}\n"
            "  Pass --force to overwrite, or --output PATH to write elsewhere."
        )

    installed = get_installed_tools(DEFAULT_SUPPORTED_TOOLS)
    content = render_initial_config(installed)

    if args.dry_run:
        print(f"[dry-run] Would write {target}:\n")
        print(content)
        return

    ensure_private_dir(target.parent)
    target.write_text(content, encoding="utf-8")
    ensure_private_file(target)
    print(f"Generated configuration: {target}")
    if installed:
        print(f"Detected agent CLIs    : {', '.join(installed)}")
    else:
        print("Detected agent CLIs    : (none found on PATH — wrote default template)")
    print("Run `ai-route doctor` (or `ai-route status --check`) anytime to verify your setup.")
